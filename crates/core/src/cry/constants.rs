/// Install all engine constants and the global bit ops.
pub fn install(lua: &Lua) -> Result<()> {
    let g = lua.globals();
    for (name, value) in ENGINE_CONSTANTS {
        g.set(*name, *value)?;
    }
    install_bit_ops(lua)?;
    Ok(())
}

/// Convert a script value to the 32/64-bit integer the bit ops use. CryEngine
/// truncates Lua numbers to `int64` before applying the operation.
fn to_i64(v: &Value) -> i64 {
    match v {
        Value::Integer(i) => *i,
        Value::Number(n) => *n as i64,
        Value::Boolean(b) => *b as i64,
        Value::String(s) => s
            .to_str()
            .ok()
            .and_then(|s| s.trim().parse::<f64>().ok())
            .unwrap_or(0.0) as i64,
        _ => 0,
    }
}

/// The original engine registers these eight global functions; the shift
/// helpers operate on full 64-bit values (`edx:eax`), returning 0 (or the
/// sign) once the count reaches 64.
fn install_bit_ops(lua: &Lua) -> Result<()> {
    let g = lua.globals();

    g.set("bnot", lua.create_function(|_, a: Value| Ok(!to_i64(&a)))?)?;
    g.set(
        "imod",
        lua.create_function(|_, (a, b): (Value, Value)| {
            let (a, b) = (to_i64(&a), to_i64(&b));
            Ok(if b == 0 { 0 } else { a.wrapping_rem(b) })
        })?,
    )?;
    g.set(
        "band",
        lua.create_function(|_, args: Variadic<Value>| {
            Ok(args.iter().map(to_i64).reduce(|acc, v| acc & v).unwrap_or(0))
        })?,
    )?;
    g.set(
        "bor",
        lua.create_function(|_, args: Variadic<Value>| {
            Ok(args.iter().map(to_i64).fold(0i64, |acc, v| acc | v))
        })?,
    )?;
    g.set(
        "bxor",
        lua.create_function(|_, args: Variadic<Value>| {
            Ok(args.iter().map(to_i64).fold(0i64, |acc, v| acc ^ v))
        })?,
    )?;
    g.set(
        "lshift",
        lua.create_function(|_, (a, b): (Value, Value)| {
            let (a, b) = (to_i64(&a), to_i64(&b));
            Ok(if b < 0 || b >= 64 { 0 } else { a.wrapping_shl(b as u32) })
        })?,
    )?;
    g.set(
        "rshift",
        lua.create_function(|_, (a, b): (Value, Value)| {
            let (a, b) = (to_i64(&a), to_i64(&b));
            Ok(if b < 0 || b >= 64 { 0 } else { ((a as u64) >> (b as u32)) as i64 })
        })?,
    )?;
    g.set(
        "arshift",
        lua.create_function(|_, (a, b): (Value, Value)| {
            let (a, b) = (to_i64(&a), to_i64(&b));
            Ok(if b < 0 || b >= 64 { if a < 0 { -1 } else { 0 } } else { a.wrapping_shr(b as u32) })
        })?,
    )?;
    Ok(())
}

